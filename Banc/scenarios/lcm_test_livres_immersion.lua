-- Navigation, interruption et rendu du lecteur autonome (sans fenetre du Kit).
local function attendu(nom, obtenu, voulu)
    assert(obtenu == voulu, nom .. " : " .. tostring(obtenu) .. " au lieu de " .. tostring(voulu))
    print("  ok  " .. nom)
end
__declencher("PLAYER_LOGIN")
local definition = { id = "livre_immersion", label = "Le dernier veilleur", format = "livre",
    pages = {} }
for i = 1, 5 do definition.pages[i] = { titre = "Chapitre " .. i, texte = "Texte de la page " .. i } end
attendu("lecture autonome", LCM.UI.Livres.Apercu(definition), true)
local f = LCM.UI.Livres.frame
attendu("aucun panneau de fond", f.fond, nil)
attendu("aucun bandeau de fenetre", f.titre, nil)
local clic = f.couverture:GetScript("OnMouseUp")
clic(f.couverture, "LeftButton")
__avancer(1.1)
attendu("couverture cliquable", f.index, 2)
f.suivant:Click()
__avancer(0.15)
attendu("feuillet en mouvement", f.tourne:IsShown(), true)
attendu("ancienne page avant mi-course", f.index, 2)
f:Tourner(1)
__avancer(1)
attendu("double clic ne saute aucune page", f.index, 4)
attendu("troisieme page", f.gauche.texte:GetText(), "Texte de la page 3")
attendu("quatrieme page", f.droite.texte:GetText(), "Texte de la page 4")
attendu("animation terminee", f.animation, nil)
f:Tourner(1)
__avancer(1.1)
attendu("cinquieme page", f.gauche.texte:GetText(), "Texte de la page 5")
attendu("page impaire sans texte fantome", f.droite:IsShown(), false)
f:Tourner(1)
__avancer(1.1)
attendu("dos atteint", f.index, 7)
f:Tourner(-1)
__avancer(1.1)
attendu("retour depuis le dos", f.index, 6)
f:Tourner(-1)
__avancer(0.2)
f:Hide()
attendu("fermeture annule le mouvement", f.animation, nil)
attendu("feuillet anime masque", f.tourne:IsShown(), false)
LCM.UI.Livres.Apercu(definition)
attendu("reouverture propre", f.index, 1)
local note = { id = "note_immersion", label = "Lettre", format = "note",
    pages = { { titre = "", texte = "recto" }, { titre = "", texte = "verso" } } }
LCM.UI.Livres.Apercu(note)
f:Tourner(1)
__avancer(1.1)
attendu("note retournee", f.note.page.texte:GetText(), "verso")
attendu("pas de titre Page invente", f.note.page.titre:GetText(), "")
attendu("pages conservees dans les donnees", #definition.pages, 5)
print("IMMERSION : TOUT PASSE")
