__declencher("PLAYER_LOGIN")
__personnage()
local L, I, UI = LCM.Lanterne, LCM.Inventaire, LCM.UI
local moi = LCM.Entities.Self()
LCM.Lanternes.Add({ id = "visuel_lanterne", label = "Lanterne visuelle", multiplicateur = 1 })
LCM.Cristaux.Add({ id = "visuel_cristal", label = "Cristal visuel", duree = 6000 })
assert(I.Deposer(moi, "lanternes/visuel_lanterne", 1))
assert(I.Deposer(moi, "cristaux/visuel_cristal", 1))
assert(UI.Ceinture.Equiper("lanternes/visuel_lanterne", 1))
UI.Ceinture.Basculer()
local belt = UI.Ceinture.frame
local crochet = belt.emplacements[1]
local f = assert(crochet.lanterne)
assert(f:IsShown() and not crochet.objetIcone:IsShown())
assert(not f.cristal:IsShown())
assert(#f.minutes.traits == 60 and #f.heures.traits == 24 and #f.jours.traits == 6)
assert(L.ChoisirCristal("visuel_cristal"))
f:Actualiser()
assert(f.etat.present and f.etat.charge == 1 and f.cristal:IsShown())
moi.cristalPose.charge = 2 * 86400 + 3 * 3600 + 4 * 60
f:Actualiser()
assert(math.floor(f.minutes.valeur) == 4 and math.floor(f.heures.valeur) == 3)
assert(math.floor(f.jours.valeur) == 2)
f.interrupteur:Click()
assert(L.Allumee() and f.etat.allumee)
moi.cristalPose.charge = 1
__avancerTemps(2)
L.Synchroniser()
f:Actualiser()
assert(not L.Allumee() and f.etat.present and f.etat.charge == 0)
assert(f.cristal:IsShown(), "un cristal epuise reste visible")
assert(L.ChoisirCristal(false))
f:Actualiser()
assert(not f.cristal:IsShown())
assert(L.RetirerLanterne())
belt:Afficher()
assert(not f:IsShown() and not f.raccord:IsShown() and crochet.plus:IsShown())
print("TOUT PASSE : ancrage, 60/24/6 traits, interrupteur, cristal plein/vide/absent")
