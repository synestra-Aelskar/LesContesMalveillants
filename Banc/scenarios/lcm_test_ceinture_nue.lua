local entree = assert(LCM.UI.Menu.Trouver("outils_portes"))
entree.onClick()
local f = assert(LCM.UI.Ceinture.frame)
assert(f:IsShown())
assert(#f.emplacements == 2)
assert(f.contenu == nil and f.equiper == nil and f.lignes == nil)
local moi = LCM.Entities.Self()
assert(LCM.Objets.Capacite("outil") == 2)
assert(LCM.Inventaire.Deposer(moi, "objets/outil_scanner_valrazkah", 1))
f.emplacements[2]:Click()
local choix = assert(LCM.UI.Ceinture.frame and _G.LCM_Choix_ceinture_outils)
assert(choix:IsShown() and choix.lignes[1].choix == "objets/outil_scanner_valrazkah")
choix.lignes[1]:Click()
assert(LCM.Objets.Porte(moi, "outil_scanner_valrazkah"))
assert(f.emplacements[2].porte.id == "outil_scanner_valrazkah")
