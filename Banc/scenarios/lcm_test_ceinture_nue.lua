assert(f.emplacements[1].plus:IsShown())
assert(not LCM.Objets.Possede(moi, "outil_scanner_valrazkah"))
assert(LCM.Inventaire.Deposer(moi, "objets/outil_scanner_valrazkah", 1))
local accepte = f.emplacements[1].glisserAccepte({
    ref = "objets/outil_scanner_valrazkah", origine = { onglet = "sacs", index = 1, case = 1 }
})
assert(accepte)
f.emplacements[1].glisserDepose({ ref = "objets/outil_scanner_valrazkah" })
assert(#LCM.Objets.Ids(moi, "outil") == 2)
assert(f.emplacements[1].porte and f.emplacements[2].porte)
assert(LCM.Objets.Desequiper(moi, "outil_scanner_valrazkah", 2))
__avancer(0.25, 0.25)
