assert(LCM.Objets.Equiper(moi, "outil_scanner_valrazkah"))
__avancer(0.25, 0.25)
assert(f.emplacements[1].porte and f.emplacements[1].objetIcone:IsShown())
entree.onClick()
assert(not f:IsShown())
